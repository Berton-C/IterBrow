#!/usr/bin/env python3
"""Export the Soul kernel for apps: iter/sdk/soul_kernel.json, read through the lens.

docs/milestones/M10_ally_sdk.md A5. The SDK (iter/sdk/iter_ally.js) carries no pattern names or
text of its own; everything it shows comes from this file, and this file comes only from the kernel
atoms through iterbrow_runtime/soul_lens.py (the AtomSpace service's "soul" view). Never edit the
JSON by hand: run this script with the service up (ITER_METTA_SOCKET set) and commit the result.

  python3 scripts/export_soul_kernel.py            # writes iter/sdk/soul_kernel.json (+ .js)
  python3 scripts/export_soul_kernel.py --out F    # writes F instead
  python3 scripts/export_soul_kernel.py --check    # exit 1 if the committed file differs
"""
import argparse
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
ITER = REPO / "iter"
DEFAULT_OUT = ITER / "sdk" / "soul_kernel.json"
# The same data as a classic script (window.IterAllyKernel), because apps run from file:// where
# Chromium refuses fetch(); the SDK loads this file next to itself with a <script> tag.
DEFAULT_JS = ITER / "sdk" / "soul_kernel.js"
sys.path.insert(0, str(ITER))

from iterbrow_runtime import soul_lens  # noqa: E402

SEED = "seeds/soul_kernel.metta"


def _text(raw):
    """Unescape a MeTTa string body as the lens returns it (\\" and \\\\)."""
    try:
        return json.loads('"%s"' % raw)
    except ValueError:
        return raw.replace('\\"', '"')


def export():
    facets = {name: soul_lens.facet(name) for name in soul_lens.FACETS}
    patterns = list(facets["description"])
    by_pattern = {pattern: {name: _text(facets[name][pattern]) for name in soul_lens.FACETS if pattern in facets[name]}
                  for pattern in patterns}
    vectors = {vector: sorted(set(threatened)) for vector, threatened in soul_lens.tension_vectors().items()}
    return {
        "generated_from": SEED,
        "patterns": patterns,
        "facets": by_pattern,
        "pairs": sorted([list(pair) for pair in soul_lens.declared_pairs()]),
        "tension_vectors": vectors,
    }


def render(kernel):
    return json.dumps(kernel, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def render_js(json_text):
    return ("// Generated by scripts/export_soul_kernel.py from seeds/soul_kernel.metta through soul_lens.\n"
            "// Do not edit. The same data as soul_kernel.json, loadable from file:// pages.\n"
            "window.IterAllyKernel = " + json_text.rstrip("\n") + ";\n")


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    parser.add_argument("--check", action="store_true", help="compare with the committed file instead of writing")
    args = parser.parse_args(argv)
    text = render(export())
    if args.check:
        current = DEFAULT_OUT.read_text(encoding="utf-8") if DEFAULT_OUT.exists() else ""
        current_js = DEFAULT_JS.read_text(encoding="utf-8") if DEFAULT_JS.exists() else ""
        if current != text or current_js != render_js(text):
            print("iter/sdk/soul_kernel.json is stale: run scripts/export_soul_kernel.py and commit it")
            return 1
        print("iter/sdk/soul_kernel.json is current")
        return 0
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(text, encoding="utf-8")
    if args.out == DEFAULT_OUT:
        DEFAULT_JS.write_text(render_js(text), encoding="utf-8")
    print("wrote %s (%d patterns)" % (args.out, len(json.loads(text)["patterns"])))
    return 0


if __name__ == "__main__":
    sys.exit(main())
